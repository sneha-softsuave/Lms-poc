/**
 * Bare icons size themselves to the surrounding font-size (`.icon svg { 1em }`),
 * so they line up inside buttons, badges and list rows without per-use styling.
 */
export function Icon({ name, className = "" }: { name: IconName; className?: string }) {
  return <span className={`icon ${className}`.trim()}>{ICONS[name]}</span>;
}

export function IconTile({
  name,
  size = "md",
  tone = "blue",
  className = "",
}: {
  name: IconName;
  size?: "sm" | "md" | "lg";
  tone?: "blue" | "green" | "amber" | "red" | "slate";
  className?: string;
}) {
  const sizeClass = size === "sm" ? "icon-tile-sm" : size === "lg" ? "icon-tile-lg" : "";
  const toneClass = tone === "blue" ? "" : `icon-tile-${tone}`;
  return (
    <div className={`icon-tile ${sizeClass} ${toneClass} ${className}`.trim()}>
      <Icon name={name} />
    </div>
  );
}
